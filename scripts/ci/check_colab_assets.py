#!/usr/bin/env python3
# =============================================================================
# scripts/ci/check_colab_assets.py
# CI gate for the Google Colab path (invoked by .github/workflows/colab.yml).
# Pure standard library — runs with the runner's python3, no project sync.
#
# Validates that the notebook, the one-line installer and the repository are
# mutually consistent:
#   1. notebook is valid JSON with a sane structure (>= 6 cells, no empty
#      code cells, no missing sources)
#   2. the notebook executes the OFFICIAL installer script
#   3. every repo-relative path the notebook references exists in the repo
#   4. the installer generates colab_wire_env.py (the Drive/GPU wiring file
#      the notebook exec()s in its cell)
#   5. every raw.githubusercontent.com / git clone URL in the installer points
#      at THIS repository (owner/repo of the canonical project)
#   6. every repo-relative path the installer references exists
# Exits non-zero with a clear failure list otherwise.
# =============================================================================
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

CANONICAL_REPO = "Alqudimi/VoiceCall"
MIN_CELLS = 6

root = Path(__file__).resolve().parents[2]
notebook_path = root / "notebooks" / "RVC_Training_Colab.ipynb"
installer_path = root / "scripts" / "colab" / "install_colab.sh"

failures: list[str] = []


def cell_source(cell) -> str:
    src = cell.get("source", "")
    if isinstance(src, list):
        return "".join(src)
    return str(src)


# ---------------------------------------------------------------- notebook ---
try:
    nb = json.loads(notebook_path.read_text(encoding="utf-8"))
except FileNotFoundError:
    sys.exit(f"FAIL: notebook not found: {notebook_path}")
except json.JSONDecodeError as exc:
    sys.exit(f"FAIL: notebook is not valid JSON: {exc}")

cells = nb.get("cells", [])
if nb.get("nbformat") not in (3, 4):
    failures.append(f"unknown nbformat: {nb.get('nbformat')!r} (expected 3 or 4)")
if len(cells) < MIN_CELLS:
    failures.append(f"notebook has only {len(cells)} cells — expected >= {MIN_CELLS}")
empty_cells = [i for i, c in enumerate(cells)
               if c.get("cell_type") == "code" and not cell_source(c).strip()]
if empty_cells:
    failures.append(f"empty code cells at indices: {empty_cells}")

nb_src = "\n".join(cell_source(c) for c in cells)

# ------------------------------------------- notebook ↔ repo file references --
repo_file_pattern = (
    r"(?:[\w\-.]+/)*(?:scripts|src|configs|notebooks)/"
    r"[\w\-./]+\.(?:sh|py|json|ipynb|yaml)"
)


def repo_relative_refs(text: str) -> list[str]:
    """Path-shaped references, with full URLs stripped out first."""
    without_urls = re.sub(r"https?://\S+", "", text)
    return sorted(set(re.findall(repo_file_pattern, without_urls)))


for ref in repo_relative_refs(nb_src):
    if not (root / ref).is_file():
        failures.append(f"notebook references a file that is missing in the repo: {ref}")

# the notebook must drive the OFFICIAL installer (not ad-hoc commands)
if "scripts/colab/install_colab.sh" not in nb_src:
    failures.append("notebook never executes scripts/colab/install_colab.sh")

# ---------------------------------------------------------------- installer --
try:
    installer = installer_path.read_text(encoding="utf-8")
except FileNotFoundError:
    sys.exit(f"FAIL: installer not found: {installer_path}")

# colab_wire_env.py is generated by the installer and exec()d by the notebook
if "colab_wire_env.py" not in installer:
    failures.append("installer does not generate colab_wire_env.py")

# raw URLs must point at the canonical repository
raw_urls = sorted(set(
    re.findall(r"https://raw\.githubusercontent\.com/([\w\-.]+)/([\w\-.]+)/", installer)
))
for owner, repo in raw_urls:
    if f"{owner}/{repo}" != CANONICAL_REPO:
        failures.append(
            f"installer references a foreign repository: {owner}/{repo} "
            f"(expected {CANONICAL_REPO})"
        )

# git clone target must be the canonical repository as well
clone_urls = sorted(set(
    re.findall(r"https://github\.com/([\w\-.]+)/([\w\-.]+)\.git", installer)
))
for owner, repo in clone_urls:
    if f"{owner}/{repo}" != CANONICAL_REPO:
        failures.append(
            f"installer clones a foreign repository: {owner}/{repo} "
            f"(expected {CANONICAL_REPO})"
        )

# repo-relative files referenced by the installer must exist
for ref in repo_relative_refs(installer):
    if not (root / ref).is_file():
        failures.append(f"installer references a file that is missing in the repo: {ref}")

# --------------------------------------------------------------- verdict -----
if failures:
    print("FAIL — Colab assets are inconsistent with the repository:")
    for f in failures:
        print(f"  - {f}")
    sys.exit(1)

print(f"OK — notebook ({len(cells)} cells) + installer are consistent "
      f"with repo {CANONICAL_REPO}")
