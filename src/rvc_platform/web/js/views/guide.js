import { el, icon } from "../api.js";

export default { mount };

async function mount(root) {
  root.replaceChildren(el("div", { class: "stack" }, [
    buildIntro(),
    buildQuickStart(),
    buildSections(),
    buildConcepts(),
    buildQuality(),
    buildTroubleshooting(),
  ]));

  function cleanup() { /* static content — no timers */ }
  return cleanup;
}

